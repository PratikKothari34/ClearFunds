import { useEffect, useState } from 'react'
import { createFileRoute, Link } from '@tanstack/react-router'
import { AlertTriangle, Printer } from 'lucide-react'
import { useReport, useYears } from '../lib/api'
import { categoryLabel, day, instant, longDay, month, opinionHint, opinionLabel, opinionTone } from '../lib/format'
import { Amount, Button, Caption, Card, Chip, Failed, Fingerprint, Loading, PageTitle, Segmented, cx } from '../components/ui'
import type { Report } from '../lib/types'

export const Route = createFileRoute('/reports')({ component: Reports })

function Reports() {
  const years = useYears()
  const [fy, setFy] = useState<string>()
  useEffect(() => {
    if (!fy && years.data?.length) setFy(years.data.at(-1)!.fy)
  }, [years.data, fy])
  const report = useReport(fy)

  return (
    <div>
      <PageTitle title="Reports" sub="Generated by the server from the chained record."
        action={<Button className="shrink-0 print:hidden" icon={<Printer className="size-4" />} onClick={() => window.print()} aria-label="Save as PDF"><span className="hidden sm:inline">Save PDF</span></Button>} />
      {years.data && years.data.length > 1 && (
        <Segmented<string> className="mb-5 print:hidden" label="Financial year" value={fy ?? ''} onChange={setFy}
          options={years.data.toReversed().map((y) => ({ value: y.fy, label: `FY ${y.fy}` }))} />
      )}
      {report.isPending ? <Loading rows={5} /> : report.isError ? <Failed error={report.error} retry={() => report.refetch()} />
        : <Body r={report.data} />}
    </div>
  )
}

function Body({ r }: { r: Report }) {
  const ie = r.income_expenditure
  const bs = r.balance_sheet
  const op = r.opinions
  return (
    <div className="space-y-6">
      <Card className="rise p-5">
        <div className="flex flex-wrap items-start justify-between gap-3">
          <div>
            <p className="text-[13px] text-ink-2">{r.society.name}{r.society.city ? `, ${r.society.city}` : ''}</p>
            <h2 className="mt-0.5 text-xl font-semibold tracking-tight">FY {r.fy}</h2>
            <p className="text-[13px] text-ink-2">{longDay(r.starts)} to {longDay(r.ends)}</p>
          </div>
          <div className="text-right">
            <Chip tone={opinionTone(op.headline)}>{op.headline ? `Audit: ${opinionLabel[op.headline]}` : 'Not yet audited'}</Chip>
          </div>
        </div>
        {op.headline && <p className="mt-3 text-sm text-ink-2">{opinionHint[op.headline]}</p>}
        <div className="mt-4 grid grid-cols-3 gap-2 text-center">
          <Mini label="Income" minor={ie.total_income_minor} className="text-credit" />
          <Mini label="Spent" minor={ie.total_expenditure_minor} className="text-debit" />
          <Mini label={ie.surplus_minor >= 0 ? 'Surplus' : 'Deficit'} minor={ie.surplus_minor} />
        </div>
      </Card>

      <section>
        <Caption>Income and expenditure</Caption>
        <Card className="p-5">
          <Table title="Income" rows={ie.income} total={ie.total_income_minor} />
          <div className="my-5 h-px bg-line" />
          <Table title="Expenditure" rows={ie.expenditure} total={ie.total_expenditure_minor} />
          <div className="mt-5 flex items-center justify-between rounded-xl bg-sunken px-4 py-3 font-semibold">
            <span>{ie.surplus_minor >= 0 ? 'Surplus for the year' : 'Deficit for the year'}</span>
            <Amount minor={ie.surplus_minor} />
          </div>
        </Card>
      </section>

      <section>
        <Caption>Balance sheet as at {longDay(r.ends)}</Caption>
        <Card className="grid gap-6 p-5 sm:grid-cols-2">
          <div>
            <h3 className="mb-2 text-[13px] font-medium text-ink-2">Funds and liabilities</h3>
            <Line label="Opening fund" minor={bs.opening_fund_minor} />
            <Line label="Add surplus" minor={bs.surplus_minor} />
            <Line label="Closing fund" minor={bs.closing_fund_minor} strong />
            {bs.advances_from_members_minor > 0 && <Line label="Advances from members" minor={bs.advances_from_members_minor} />}
            <Line label="Total" minor={bs.total_funds_and_liabilities_minor} total />
          </div>
          <div>
            <h3 className="mb-2 text-[13px] font-medium text-ink-2">Assets</h3>
            <Line label="Cash and bank" minor={bs.cash_and_bank_minor} />
            <Line label="Dues receivable from flats" minor={bs.dues_receivable_minor} />
            <Line label="Total" minor={bs.total_assets_minor} total />
          </div>
        </Card>
        <p className="mt-3 px-1 text-[13px] leading-relaxed text-ink-2">{r.true_and_fair}</p>
      </section>

      <section>
        <Caption>Adjusting entries against closed years</Caption>
        <Card className={cx('p-5', r.adjusting_entries.length > 0 && 'border-break/25')}>
          {r.adjusting_entries.length ? (
            <>
              <p className="mb-3 flex items-center gap-2 text-sm font-medium text-break"><AlertTriangle className="size-4" />To be disclosed at the AGM</p>
              <ul className="divide-y divide-line">
                {r.adjusting_entries.map((a) => (
                  <li key={a.seq} className="py-3 text-sm">
                    <div className="flex items-center justify-between gap-3">
                      <Link to="/entry/$seq" params={{ seq: String(a.seq) }} className="font-medium text-accent">#{a.seq} corrects FY {a.corrects_fy}</Link>
                      <Amount minor={a.amount_minor} signed />
                    </div>
                    <p className="mt-1 text-ink-2">{a.counterparty}: {a.reason}</p>
                  </li>
                ))}
              </ul>
              <p className="mt-3 text-[13px] text-ink-2">Posted in this year. The closed year’s filed figures are unchanged.</p>
            </>
          ) : <p className="text-sm text-ink-2">None this year.</p>}
        </Card>
      </section>

      <section>
        <Caption>Reversals</Caption>
        <Card className="p-5">
          {r.reversals.length ? (
            <ul className="divide-y divide-line">
              {r.reversals.map((x) => (
                <li key={x.seq} className="py-3 text-sm">
                  <div className="flex items-center justify-between gap-3">
                    <Link to="/entry/$seq" params={{ seq: String(x.seq) }} className="font-medium">#{x.seq} reverses #{x.reverses_seq}, {x.counterparty}</Link>
                    <Amount minor={x.amount_minor} signed />
                  </div>
                  <p className="mt-1 text-ink-2">{day(x.business_date)}: {x.reason}</p>
                </li>
              ))}
            </ul>
          ) : <p className="text-sm text-ink-2">No reversals this year.</p>}
          <p className="mt-3 text-[13px] text-ink-2">Every reversal appears here, with its original. Nothing is left out of the report.</p>
        </Card>
      </section>

      <section>
        <Caption>Payments that add up past the limit</Caption>
        <Card className="p-5">
          {r.structuring.length ? r.structuring.map((g) => (
            <div key={g.counterparty + g.first_date} className="py-2 text-sm">
              <div className="flex items-center justify-between gap-3">
                <Link to="/ledger" search={{ q: g.counterparty }} className="font-medium">{g.counterparty}</Link>
                <Amount minor={g.total_minor} />
              </div>
              <p className="mt-1 text-ink-2">
                {g.constituents.length} below-limit payments, {day(g.first_date)} to {day(g.last_date)}, together above the <Amount minor={g.limit_minor} size="sm" /> limit.
              </p>
            </div>
          )) : <p className="text-sm text-ink-2">None this year.</p>}
          <p className="mt-3 text-[13px] text-ink-2">Shown, not blocked. A genuine run of small repairs looks the same; the committee explains it at the AGM.</p>
        </Card>
      </section>

      <section>
        <Caption>Auditor’s opinion</Caption>
        <Card className="p-5">
          {op.history.length ? op.history.map((h) => (
            <div key={h.seq} className="py-2">
              <div className="flex items-center justify-between gap-3">
                <span className="text-sm font-medium">{h.auditor}</span>
                <Chip tone={opinionTone(h.opinion)}>{opinionLabel[h.opinion]}{h.seq === op.headline_seq && op.history.length > 1 ? ', governs' : ''}</Chip>
              </div>
              <p className="mt-2 text-sm leading-relaxed text-ink-2">{h.statement}</p>
              <p className="mt-1 text-xs text-ink-2">Signed {instant(h.recorded_at)} · #{h.seq}</p>
            </div>
          )) : <p className="text-sm text-ink-2">No opinion yet. Only the appointed auditor closes the year.</p>}
          <p className="mt-3 text-[13px] text-ink-2">An audit gives reasonable assurance, not a guarantee.</p>
        </Card>
      </section>

      {r.signoffs.length > 0 && (
        <section>
          <Caption>President’s monthly sign-off</Caption>
          <Card className="flex flex-wrap gap-2 p-5">
            {r.signoffs.map((s) => <Chip key={s.month} tone="anchor">{month(s.month, { month: 'short', year: '2-digit' })}</Chip>)}
          </Card>
        </section>
      )}

      <Card className="flex flex-wrap items-center justify-between gap-3 p-4 text-[13px] text-ink-2">
        <span>Generated {instant(r.generated_at)} through entry #{r.through_seq}</span>
        <Fingerprint value={r.through_hash} />
      </Card>
    </div>
  )
}

function Mini({ label, minor, className }: { label: string; minor: number; className?: string }) {
  return (
    <div className="rounded-xl bg-sunken px-2 py-3">
      <Amount minor={minor} size="sm" className={cx('font-semibold', className)} />
      <p className="text-xs text-ink-2">{label}</p>
    </div>
  )
}

function Table({ title, rows, total }: { title: string; rows: { category: string; amount_minor: number }[]; total: number }) {
  return (
    <div>
      <h3 className="mb-2 text-[13px] font-medium text-ink-2">{title}</h3>
      {rows.length ? rows.map((x) => <Line key={x.category} label={categoryLabel(x.category)} minor={x.amount_minor} />)
        : <p className="text-sm text-ink-2">None.</p>}
      <Line label={`Total ${title.toLowerCase()}`} minor={total} total />
    </div>
  )
}

function Line({ label, minor, strong, total }: { label: string; minor: number; strong?: boolean; total?: boolean }) {
  return (
    <div className={cx('flex items-baseline justify-between gap-3 py-1.5 text-sm', total && 'mt-1 border-t border-line pt-2.5 font-semibold', strong && 'font-medium')}>
      <span>{label}</span>
      <Amount minor={minor} size="sm" className={cx((total || strong) && 'font-semibold')} />
    </div>
  )
}
